# ── Authentication ────────────────────────────────────────────────────────────

def oa_login() -> str:
    """
    POST /api/login  →  returns a JWT token (valid 2 days).
    Credentials are read from .env:
        OA_USERNAME = <email or username>
        OA_PASSWORD = <password>
    """
    username = os.getenv("OA_USERNAME")
    password = os.getenv("OA_PASSWORD")

    if not username or not password:
        raise ValueError(
            "OA_USERNAME and OA_PASSWORD must be set in the .env file "
            "located in the same folder as this notebook."
        )

    r = requests.post(
        f"{_OA_API}/login",
        json={"username": username, "password": password},
        timeout=30,
    )
    r.raise_for_status()
    data = r.json()

    token = data.get("token")
    if not token:
        raise ValueError(f"Login failed – no token in response: {data}")

    print(f"Logged in as '{data.get('username', username)}'  "
          f"(level: {data.get('level', '?')}, access: {data.get('access', '?')})")
    return token


# ── Source discovery ──────────────────────────────────────────────────────────

def oa_find_all_sources(sample_points: list, state_abbr: str) -> list:
    """
    Query GET /api/data?point=…&layer=addresses for each point in sample_points
    and collect every unique OA source (deduplicated by job_id) that belongs
    to the correct state (source path starts with 'us/{state_abbr}/').

    Parameters
    ----------
    sample_points : list of (lon, lat) tuples
    state_abbr    : lowercase state abbreviation, e.g. 'ny'

    Returns
    -------
    list of unique OA catalog entries (dicts) for the correct state
    """
    prefix    = f"us/{state_abbr}/"
    seen_jobs = set()
    entries   = []

    for lon, lat in sample_points:
        r = requests.get(
            f"{_OA_API}/data",
            params={"point": f"{lon},{lat}", "layer": "addresses"},
            timeout=30,
        )
        r.raise_for_status()

        for entry in r.json():
            if not entry.get("source", "").startswith(prefix):
                continue
            job_id = entry.get("job")
            if job_id not in seen_jobs:
                seen_jobs.add(job_id)
                entries.append(entry)

    return entries


# ── Download ──────────────────────────────────────────────────────────────────

def oa_download_job(job_id: int, token: str) -> gpd.GeoDataFrame:
    """
    GET /api/job/{job_id}/output/source.geojson.gz  (requires Bearer token)

    Streams the gzip-compressed GeoJSON to a temp file, decompresses it to
    a plain .geojson, reads into a GeoDataFrame (EPSG:4326), then deletes
    both temp files.

    OA column names are fixed uppercase:
        NUMBER, STREET, UNIT, CITY, DISTRICT, REGION, POSTCODE, ID, HASH
    """
    url = f"{_OA_API}/job/{job_id}/output/source.geojson.gz"

    with tempfile.TemporaryDirectory() as tmpdir:
        gz_path      = Path(tmpdir) / f"oa_{job_id}.geojson.gz"
        geojson_path = Path(tmpdir) / f"oa_{job_id}.geojson"

        with requests.get(
            url,
            headers={"Authorization": f"Bearer {token}"},
            timeout=600,
            stream=True,
        ) as r:
            r.raise_for_status()
            with open(gz_path, "wb") as f:
                for chunk in r.iter_content(chunk_size=65536):
                    f.write(chunk)

        # Decompress: pyogrio/GDAL does not handle .geojson.gz directly
        with gzip.open(gz_path, "rb") as gz_in, open(geojson_path, "wb") as json_out:
            json_out.write(gz_in.read())

        gdf = gpd.read_file(geojson_path)
        # tmpdir (gz + geojson) auto-deleted on context exit
        return gdf


# ── Deduplication helper ──────────────────────────────────────────────────────

def _deduplicate(gdf: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    """
    Remove duplicate address points.

    Strategy (in order of preference):
      1. HASH column  — OA content hash, unique per address record. Most
                        reliable but not always present in every dataset.
      2. Geometry WKT — two points at identical coordinates are the same
                        physical address. Used as fallback when HASH is absent.
    """
    # Case-insensitive search for a HASH column
    hash_col = next((c for c in gdf.columns if c.upper() == "HASH"), None)

    if hash_col:
        deduped = gdf.drop_duplicates(subset=[hash_col])
    else:
        deduped = gdf.copy()
        deduped["_wkt"] = deduped.geometry.to_wkt()
        deduped = deduped.drop_duplicates(subset=["_wkt"]).drop(columns=["_wkt"])

    return deduped.reset_index(drop=True)


# ── Main retrieval function ───────────────────────────────────────────────────

def retrieve_oa_for_nsi(nsi_gdf: gpd.GeoDataFrame) -> gpd.GeoDataFrame:
    """
    Retrieve all OpenAddresses data that fully covers the NSI buildings and
    return it as a single, deduplicated GeoDataFrame.

    For each unique Census tract in nsi_gdf:
      1. Compute the bounding box of its NSI points
      2. Sample 5 points (4 corners + centroid) and query the OA API
      3. Download every unique OA source found (filtered to the correct state)
      4. Clip the result to the tract bounding box to discard addresses that
         are far outside the area of interest (e.g. from a statewide dataset)

    After processing all tracts, all per-tract GeoDataFrames are concatenated
    and deduplicated. Points that fell in more than one tract's bounding box
    (adjacent tracts with overlapping boxes) are reduced to a single row.

    Downloads are deduplicated globally: if the same OA job covers multiple
    tracts, the file is downloaded only once.

    Parameters
    ----------
    nsi_gdf : GeoDataFrame with a 'census_tract' column (11-digit GEOID).

    Returns
    -------
    GeoDataFrame  — all unique OA address points covering the NSI area (EPSG:4326)
    """
    token = oa_login()
    print()

    unique_tracts = nsi_gdf["census_tract"].unique()
    print(f"Tracts to process: {list(unique_tracts)}\n")

    job_cache    = {}   # {job_id: GeoDataFrame} – avoids duplicate downloads
    tract_slices = []   # per-tract filtered GeoDataFrames, collected for final merge

    for tract_geoid in unique_tracts:

        state_fips = tract_geoid[:2]
        state_abbr = _STATE_FIPS_TO_ABBR.get(state_fips)
        if state_abbr is None:
            print(f"Tract {tract_geoid}: unknown state FIPS '{state_fips}'. Skipping.\n")
            continue

        mask   = nsi_gdf["census_tract"] == tract_geoid
        subset = nsi_gdf.loc[mask]

        # Bounding box of the NSI points for this tract
        minx, miny, maxx, maxy = subset.total_bounds
        cx, cy = (minx + maxx) / 2, (miny + maxy) / 2

        sample_points = [
            (minx, miny), (minx, maxy),   # SW, NW
            (maxx, miny), (maxx, maxy),   # SE, NE
            (cx,   cy  ),                 # centre
        ]

        print(f"Tract {tract_geoid} ({state_abbr.upper()}):")
        print(f"  Bounding box: ({minx:.4f}, {miny:.4f}) → ({maxx:.4f}, {maxy:.4f})")
        print(f"  Querying OA API at 5 sample points …")

        entries = oa_find_all_sources(sample_points, state_abbr)

        if not entries:
            print(f"  No OA sources found for state '{state_abbr}'. Skipping.\n")
            continue

        print(f"  Found {len(entries)} unique OA source(s): "
              f"{[e['source'] for e in entries]}")

        # Download each unique source
        tract_gdfs = []
        for entry in entries:
            job_id  = entry["job"]
            source  = entry["source"]
            size_mb = (entry.get("size") or 0) / 1e6

            if job_id not in job_cache:
                print(f"  Downloading '{source}'  (job {job_id}, {size_mb:.1f} MB) …")
                job_cache[job_id] = oa_download_job(job_id, token)
                print(f"    → {len(job_cache[job_id]):,} addresses loaded. Temp file deleted.")
            else:
                print(f"  '{source}'  (job {job_id}) already in memory – reusing.")

            tract_gdfs.append(job_cache[job_id])

        # Merge sources for this tract, then clip to the tract bounding box.
        # cx[] uses coordinate indexing: retains only points whose (lon, lat)
        # falls within [minx, maxx] × [miny, maxy].
        tract_oa = (
            gpd.GeoDataFrame(pd.concat(tract_gdfs, ignore_index=True), crs="EPSG:4326")
            if len(tract_gdfs) > 1
            else tract_gdfs[0]
        )
        tract_oa = tract_oa.cx[minx:maxx, miny:maxy]
        print(f"  After bounding-box clip: {len(tract_oa):,} addresses retained.\n")

        tract_slices.append(tract_oa)

    if not tract_slices:
        print("No OA data retrieved.")
        return gpd.GeoDataFrame(crs="EPSG:4326")

    # Concatenate all per-tract slices and deduplicate
    oa_combined = gpd.GeoDataFrame(
        pd.concat(tract_slices, ignore_index=True),
        crs="EPSG:4326"
    )
    n_before = len(oa_combined)
    oa_combined = _deduplicate(oa_combined)
    n_after = len(oa_combined)

    print(f"Combined: {n_before:,} rows → {n_after:,} after deduplication "
          f"({n_before - n_after:,} duplicates removed).")

    return oa_combined

