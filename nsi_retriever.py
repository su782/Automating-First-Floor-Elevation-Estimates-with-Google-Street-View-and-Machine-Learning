TIGER_TRACT_URL = (
    "https://tigerweb.geo.census.gov/arcgis/rest/services/"
    "TIGERweb/tigerWMS_Census2020/MapServer/6/query"
)


def fetch_tract_geometry(geoid: str) -> dict:
    """
    Return a GeoJSON Feature for the Census tract identified by its 11-digit
    GEOID (state-2 + county-3 + tract-6, e.g. '36059518900').
    Queries the Census TIGER 2020 web API; no extra Python package required.
    """
    params = {
        "where": f"GEOID='{geoid}'",
        "outFields": "GEOID,NAME",
        "outSR": "4326",
        "f": "geojson",
    }
    r = httpx.get(TIGER_TRACT_URL, params=params, timeout=30, follow_redirects=True)
    r.raise_for_status()
    features = r.json().get("features", [])
    if not features:
        raise ValueError(
            f"No Census tract found for GEOID '{geoid}'. "
            "Check that state/county/tract codes are correct."
        )
    return features[0]


def fetch_nsi_by_polygon(geojson_feature: dict, label: str = "polygon",
                         timeout_s: int = 300) -> gpd.GeoDataFrame:
    """
    Download NSI structures within a polygon via the NSI POST endpoint.

    Parameters
    ----------
    geojson_feature : GeoJSON Feature dict with Polygon / MultiPolygon geometry
    label           : label shown in the progress bar
    timeout_s       : request timeout in seconds
    """
    body = {"type": "FeatureCollection", "features": [geojson_feature]}
    features = []

    with httpx.stream(
        "POST",
        NSI_STRUCTURES_URL,
        params={"fmt": "fs"},
        json=body,
        timeout=timeout_s,
        follow_redirects=True,
    ) as r:
        r.raise_for_status()
        with tqdm(unit=" structures", desc=f"  {label}", leave=True,
                  mininterval=0.5) as pbar:
            for line in r.iter_lines():
                line = line.strip()
                if line:
                    features.append(json.loads(line))
                    pbar.update(1)

    if not features:
        print("  No structures returned – check that the polygon is valid.")
        return gpd.GeoDataFrame()

    return gpd.GeoDataFrame.from_features(features, crs="EPSG:4326")


